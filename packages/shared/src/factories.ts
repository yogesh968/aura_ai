/**
 * Build a complete new entity record. `id` must be a UUID v4 generated by the
 * caller (crypto.randomUUID on the server, expo-crypto on the device).
 */
export function buildEntity<T extends EntityType>(
  type: T,
  id: string,
  input: Partial<EntityInput<T>>,
  now: Date = new Date(),
): EntityMap[T] {
  const iso = now.toISOString();
  return {
    ...(entityDefaults[type] as object),
    ...(input as object),
    id,
    createdAt: iso,
    updatedAt: iso,
    deletedAt: null,
    version: 0,
  } as EntityMap[T];
}

